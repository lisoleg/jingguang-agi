def verify_theorem_t219() -> Dict:
    """Verify Theorem T2.19: L3 beta-rewire must change topology.

    Constructs a graph, performs beta-rewire on both CONTRADICTION
    and MIS_MATCH anomalies, and asserts that:
    1. The Laplacian spectrum changes after each rewire
    2. The number of edges changes (topology, not just weights)
    3. The version increments

    Returns:
        Dict with 'verified' key (True/False) and details.
    """
    result: Dict = {"verified": False, "details": []}

    try:
        # Test 1: CONTRADICTION rewire
        g = JinlingGraph()
        g.add_edge(PortEdge("A", "B", 0, 1, "init"))
        g.add_edge(PortEdge("B", "C", 1, 2, "init"))
        g.add_edge(PortEdge("C", "A", 2, 0, "init"))

        spectrum_before = g.laplacian_spectrum()
        edges_before = g.edge_count()

        delta = DeltaPsi(kind="CONTRADICTION", focus="B", magnitude=1.0)
        patch = ICEPatch(target="L3_GRAPH", action="split", data={"focus": "B"})
        g.beta_rewire(delta, patch)

        spectrum_after = g.laplacian_spectrum()
        edges_after = g.edge_count()

        spectrum_changed = any(
            abs(b - a) > 1e-3
            for b, a in zip(spectrum_before, spectrum_after)
        )
        edges_changed = edges_before != edges_after
        version_incremented = g.version == 1

        detail1 = {
            "test": "CONTRADICTION rewire",
            "spectrum_before": spectrum_before,
            "spectrum_after": spectrum_after,
            "spectrum_changed": spectrum_changed,
            "edges_before": edges_before,
            "edges_after": edges_after,
            "edges_changed": edges_changed,
            "version": g.version,
        }
        result["details"].append(detail1)

        # Test 2: MIS_MATCH rewire
        g2 = JinlingGraph()
        g2.add_edge(PortEdge("X", "Y", 0, 1, "init"))
        g2.add_edge(PortEdge("Y", "Z", 1, 2, "init"))
        g2.add_edge(PortEdge("Z", "X", 2, 0, "init"))

        spectrum_before2 = g2.laplacian_spectrum()
        edges_before2 = g2.edge_count()

        delta2 = DeltaPsi(kind="MIS_MATCH", focus="Y", magnitude=0.5)
        patch2 = ICEPatch(target="L3_GRAPH", action="rewire_port", data={"focus": "Y"})
        g2.beta_rewire(delta2, patch2)

        spectrum_after2 = g2.laplacian_spectrum()
        edges_after2 = g2.edge_count()

        spectrum_changed2 = any(
            abs(b - a) > 1e-3
            for b, a in zip(spectrum_before2, spectrum_after2)
        )
        edges_changed2 = edges_before2 != edges_after2
        version_incremented2 = g2.version == 1

        detail2 = {
            "test": "MIS_MATCH rewire",
            "spectrum_before": spectrum_before2,
            "spectrum_after": spectrum_after2,
            "spectrum_changed": spectrum_changed2,
            "edges_before": edges_before2,
            "edges_after": edges_after2,
            "edges_changed": edges_changed2,
            "version": g2.version,
        }
        result["details"].append(detail2)

        # Overall verification
        result["verified"] = (
            spectrum_changed and edges_changed and version_incremented
            and spectrum_changed2 and edges_changed2 and version_incremented2
        )

    except AssertionError as e:
        result["details"].append({"error": str(e)})
        result["verified"] = False
    except Exception as e:
        result["details"].append({"error": f"Unexpected: {e}"})
        result["verified"] = False

    return result


