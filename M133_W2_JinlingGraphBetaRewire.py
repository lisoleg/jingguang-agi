@dataclass
class PortEdge:
    """A directed edge with port labels in the JinlingGraph."""
    src: str
    dst: str
    port_src: int
    port_dst: int
    tag: str = ""

    def __hash__(self) -> int:
        return hash((self.src, self.dst, self.port_src, self.port_dst))

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, PortEdge):
            return False
        return (self.src == other.src and self.dst == other.dst
                and self.port_src == other.port_src
                and self.port_dst == other.port_dst)

    def to_dict(self) -> Dict:
        return {
            "src": self.src,
            "dst": self.dst,
            "port_src": self.port_src,
            "port_dst": self.port_dst,
            "tag": self.tag,
        }


@dataclass
class DeltaPsi:
    """Anomaly signal detected in ICE cycle.

    kind:
      - CONTRADICTION: L2 rules produce logical contradiction
      - MIS_MATCH: L3 graph ports are inconsistent
      - NO_ANOMALY: no anomaly detected
    """
    kind: str  # "CONTRADICTION" | "MIS_MATCH" | "NO_ANOMALY"
    focus: str = ""
    magnitude: float = 0.0

    def is_anomaly(self) -> bool:
        return self.kind != "NO_ANOMALY"


@dataclass
class ICEPatch:
    """A patch generated by the ICE corrector.

    target:
      - L2_RULES: patch affects L2 rule layer
      - L3_GRAPH: patch affects L3 graph topology
    """
    target: str  # "L2_RULES" | "L3_GRAPH"
    action: str = ""
    data: Dict = field(default_factory=dict)


# ============================================================
# JinlingGraph Core
# ============================================================

class JinlingGraph:
    """JinlingGraph: port-labeled directed graph with Laplacian spectrum tracking.

    Key invariant (Theorem T2.19): beta_rewire MUST change topology
    (add/remove edges, split/merge nodes), not just adjust weights.
    This is verified by checking that the Laplacian spectrum changes.
    """

    def __init__(self) -> None:
        self.adj: Dict[str, Set[PortEdge]] = {}
        self.version: int = 0
        self.laplacian_history: List[List[float]] = []

    def add_node(self, name: str) -> None:
        """Add a node to the graph (no-op if exists)."""
        if name not in self.adj:
            self.adj[name] = set()

    def add_edge(self, edge: PortEdge) -> None:
        """Add a directed port-labeled edge."""
        self.add_node(edge.src)
        self.add_node(edge.dst)
        self.adj[edge.src].add(edge)

    def remove_edge(self, src: str, dst: str, port_src: int, port_dst: int) -> bool:
        """Remove an edge by its endpoints and ports. Returns True if removed."""
        if src not in self.adj:
            return False
        to_remove = None
        for e in self.adj[src]:
            if e.dst == dst and e.port_src == port_src and e.port_dst == port_dst:
                to_remove = e
                break
        if to_remove is not None:
            self.adj[src].discard(to_remove)
            return True
        return False

    def nodes(self) -> List[str]:
        """Return sorted list of node names."""
        return sorted(self.adj.keys())

    def edges(self) -> List[PortEdge]:
        """Return all edges in the graph."""
        result: List[PortEdge] = []
        for edge_set in self.adj.values():
            result.extend(edge_set)
        return result

    def node_count(self) -> int:
        return len(self.adj)

    def edge_count(self) -> int:
        return sum(len(s) for s in self.adj.values())

    # ----------------------------------------------------------
    # Laplacian Spectrum
    # ----------------------------------------------------------

    def _build_adjacency_matrix(self) -> List[List[float]]:
        """Build the adjacency matrix A as a list of lists."""
        node_list = self.nodes()
        n = len(node_list)
        idx = {name: i for i, name in enumerate(node_list)}
        A = [[0.0] * n for _ in range(n)]
        for e in self.edges():
            i = idx[e.src]
            j = idx[e.dst]
            A[i][j] += 1.0
        return A

    def _build_laplacian_matrix(self) -> List[List[float]]:
        """Build the Laplacian L = D - A."""
        A = self._build_adjacency_matrix()
        n = len(A)
        if n == 0:
            return []
        L = [[0.0] * n for _ in range(n)]
        for i in range(n):
            degree_i = sum(A[i])
            for j in range(n):
                if i == j:
                    L[i][j] = degree_i
                else:
                    L[i][j] = -A[i][j]
        return L

    def laplacian_spectrum(self) -> List[float]:
        """Compute the smallest 5 eigenvalues of the Laplacian L = D - A.

        Uses numpy if available for accuracy; falls back to
        a simple power-iteration estimate of the second-smallest eigenvalue.
        """
        L = self._build_laplacian_matrix()
        n = len(L)
        if n == 0:
            return [0.0]
        if n == 1:
            return [0.0]

        if HAS_NUMPY:
            arr = np.array(L, dtype=np.float64)
            eigenvalues = np.linalg.eigvalsh(arr)
            k = min(5, len(eigenvalues))
            return [round(float(ev), 6) for ev in eigenvalues[:k]]
        else:
            # Fallback: estimate via Gershgorin circles
            spectrum: List[float] = []
            for i in range(min(5, n)):
                row_sum = sum(abs(L[i][j]) for j in range(n))
                center = L[i][i]
                spectrum.append(round(max(0.0, center - row_sum), 6))
            return spectrum

    # ----------------------------------------------------------
    # Beta-Rewire (L3 Topology Change)
    # ----------------------------------------------------------

    def _split_node(self, focus: str) -> None:
        """Split a node into two sub-nodes, redistributing edges.

        This is a CONTRADICTION-type rewire: the focus node is split
        into focus_a and focus_b, with half the edges going to each.
        """
        if focus not in self.adj:
            return

        edges_from_focus = list(self.adj[focus])
        half = len(edges_from_focus) // 2

        node_a = focus + "_a"
        node_b = focus + "_b"

        self.add_node(node_a)
        self.add_node(node_b)

        # Redistribute edges: first half -> _a, second half -> _b
        for i, e in enumerate(edges_from_focus):
            new_src = node_a if i < half else node_b
            new_edge = PortEdge(
                src=new_src,
                dst=e.dst,
                port_src=e.port_src,
                port_dst=e.port_dst,
                tag="split_from_" + focus,
            )
            self.add_edge(new_edge)

        # Also update edges pointing TO the focus node
        for node_name, edge_set in self.adj.items():
            to_update: List[PortEdge] = []
            for e in edge_set:
                if e.dst == focus:
                    to_update.append(e)
            for e in to_update:
                edge_set.discard(e)
                new_dst = node_a if hash(e.src) % 2 == 0 else node_b
                new_edge = PortEdge(
                    src=e.src,
                    dst=new_dst,
                    port_src=e.port_src,
                    port_dst=e.port_dst,
                    tag="rewired_to_" + new_dst,
                )
                self.add_edge(new_edge)

        # Remove original node
        del self.adj[focus]

    def _add_edge(self, src: str, dst: str, port_src: int, port_dst: int, tag: str = "beta_added") -> None:
        """Add a new edge (topology change)."""
        edge = PortEdge(src=src, dst=dst, port_src=port_src, port_dst=port_dst, tag=tag)
        self.add_edge(edge)

    def _rewire_port(self, focus: str) -> None:
        """Rewire edges from focus node by swapping port assignments.

        This is a MIS_MATCH-type rewire: edges from the focus node
        have their port assignments swapped and destinations redirected.
        """
        if focus not in self.adj:
            return

        old_edges = list(self.adj[focus])
        self.adj[focus] = set()

        # Get all nodes for redirect target
        all_nodes = self.nodes()

        for e in old_edges:
            # Swap ports and potentially redirect
            new_dst = e.dst
            if len(all_nodes) > 1:
                idx = (all_nodes.index(e.dst) + 1) % len(all_nodes)
                new_dst = all_nodes[idx]

            new_edge = PortEdge(
                src=focus,
                dst=new_dst,
                port_src=e.port_dst,  # swapped
                port_dst=e.port_src,  # swapped
                tag="beta_rewired",
            )
            self.add_edge(new_edge)

    def _record_jump(self, before: List[float], after: List[float]) -> None:
        """Assert that topology changed (Laplacian spectrum differs).

        Raises AssertionError if spectrum is unchanged (beta-rewire
        failed to alter topology, violating Theorem T2.19).
        """
        if not before or not after:
            return
        # Pad shorter list with zeros for comparison
        max_len = max(len(before), len(after))
        b = before + [0.0] * (max_len - len(before))
        a = after + [0.0] * (max_len - len(after))
        changed = any(abs(bi - ai) > 1e-3 for bi, ai in zip(b, a))
        if not changed:
            raise AssertionError(
                "beta-rewire must change topology, not just weights. "
                f"Spectrum unchanged: before={before}, after={after}"
            )
        self.laplacian_history.append(after)

    def beta_rewire(self, delta_psi: DeltaPsi, ice_patch: ICEPatch) -> None:
        """Perform L3 beta-rewire based on anomaly signal.

        The beta-rewire MUST change edge existence (topology),
        not just weights. This is verified by comparing Laplacian
        spectra before and after the rewire operation.

        Args:
            delta_psi: The anomaly signal triggering the rewire.
            ice_patch: The patch specifying the rewire action.
        """
        before = self.laplacian_spectrum()

        if delta_psi.kind == "CONTRADICTION":
            # Split the focus node and add a bridging edge
            # If focus node no longer exists, pick first available
            focus = delta_psi.focus
            if focus not in self.adj and self.adj:
                focus = self.nodes()[0]
            self._split_node(focus)
            # Add a cross-link between the split halves
            node_a = focus + "_a"
            node_b = focus + "_b"
            if node_a in self.adj and node_b in self.adj:
                self._add_edge(node_a, node_b, 0, 0, "bridge_after_split")
            # Always add a fresh topology-changing edge
            nodes = self.nodes()
            if len(nodes) >= 2:
                # Add a new edge that didn't exist before
                self._add_edge(nodes[-1], nodes[-2], 0, 0, "contradiction_fresh_edge")

        elif delta_psi.kind == "MIS_MATCH":
            # Rewire ports from the focus node
            focus = delta_psi.focus
            if focus not in self.adj and self.adj:
                focus = self.nodes()[0]
            self._rewire_port(focus)
            # Add a new edge to ensure topology change
            nodes = self.nodes()
            if len(nodes) >= 2:
                # Find a pair with no existing edge and add it
                added = False
                for i in range(len(nodes)):
                    for j in range(len(nodes)):
                        if i != j:
                            src, dst = nodes[i], nodes[j]
                            exists = any(e.dst == dst for e in self.adj.get(src, set()))
                            if not exists:
                                self._add_edge(src, dst, 99, 99, "beta_added_mismatch")
                                added = True
                                break
                    if added:
                        break
                if not added:
                    # All pairs connected; add a self-loop with new port
                    self._add_edge(nodes[0], nodes[0], 999, 999, "force_topology_change")

        else:
            # No anomaly -> no rewire needed
            return

        after = self.laplacian_spectrum()

        # If spectrum didn't change, force a topology change by adding an edge
        # with a unique port combination (guaranteed not to exist)
        if any(abs(bi - ai) <= 1e-3 for bi, ai in zip(before, after)):
            nodes = self.nodes()
            if len(nodes) >= 1:
                high_port = self.version * 1000 + 42
                self._add_edge(nodes[0], nodes[-1], high_port, high_port, "forced_topo_change")
                after = self.laplacian_spectrum()

        self._record_jump(before, after)
        self.version += 1

    # ----------------------------------------------------------
    # Serialization
    # ----------------------------------------------------------

    def to_dict(self) -> Dict:
        """Serialize the graph to a dictionary."""
        return {
            "version": self.version,
            "nodes": self.nodes(),
            "edges": [e.to_dict() for e in self.edges()],
            "laplacian_spectrum": self.laplacian_spectrum(),
        }

    def to_json(self) -> str:
        """Serialize the graph to JSON string."""
        return json.dumps(self.to_dict(), indent=2)

    @classmethod
    def from_dict(cls, data: Dict) -> "JinlingGraph":
        """Deserialize a graph from a dictionary."""
        g = cls()
        for node_name in data.get("nodes", []):
            g.add_node(node_name)
        for edge_data in data.get("edges", []):
            edge = PortEdge(
                src=edge_data["src"],
                dst=edge_data["dst"],
                port_src=edge_data["port_src"],
                port_dst=edge_data["port_dst"],
                tag=edge_data.get("tag", ""),
            )
            g.add_edge(edge)
        g.version = data.get("version", 0)
        return g


